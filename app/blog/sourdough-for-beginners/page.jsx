      <p className="mb-4">The <strong>float test</strong>: drop a small spoonful of starter into a glass of room-temperature water. If it floats, it is ready to bake. If it sinks, give it another day or two. Some starters take 10-14 days to fully activate, especially in cold kitchens.</p>

